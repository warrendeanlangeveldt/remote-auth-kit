// Copies shared files into the two places that can't import from outside
// their own folder: the unpacked extension and the static phone page. Then pins
// the phone page: the extension refuses to use an approval page whose files
// don't hash to a version listed in extension/lib/phone-pins.js.
//   node scripts/build.mjs           write the copies and add the current pin
//   node scripts/build.mjs --check   fail if a copy or the pin is out of date
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const copies = [
  ['extension/lib/relay-crypto.js', 'phone/relay-crypto.js'],
  ['node_modules/qrcode-generator/dist/qrcode.mjs', 'extension/vendor/qrcode.mjs'],
];
const check = process.argv.includes('--check');
let stale = 0;
for (const [from, to] of copies) {
  const src = join(root, from), dst = join(root, to);
  if (!existsSync(src)) {
    if (check && existsSync(dst)) continue; // dev dependency not installed; the committed copy stands
    throw new Error(`missing ${from} (run npm install)`);
  }
  const body = readFileSync(src);
  if (existsSync(dst) && readFileSync(dst).equals(body)) continue;
  if (check) { console.error(`${to} is out of date: run npm run build`); stale++; continue; }
  mkdirSync(dirname(dst), { recursive: true });
  writeFileSync(dst, body);
  console.log(`${from} -> ${to}`);
}

// ---------- phone page pin ----------
// Same digest as phonePageProblem() in extension/background.js.
const KEEP_PINS = 5; // earlier versions still accepted, so a phone page and extension can be released in either order
const sha = (b) => createHash('sha256').update(b).digest('hex');
const files = readdirSync(join(root, 'phone')).filter((f) => !f.startsWith('.')).sort();
const digest = sha(files.map((f) => `${f} ${sha(readFileSync(join(root, 'phone', f)))}\n`).join(''));
const pinsFile = join(root, 'extension/lib/phone-pins.js');
const old = existsSync(pinsFile) ? readFileSync(pinsFile, 'utf8') : '';
const pins = JSON.parse(/PHONE_PINS = (\[[^\]]*\])/.exec(old)?.[1] || '[]');
const sameFiles = old.includes(`PHONE_FILES = ${JSON.stringify(files)};`);
if (!pins.includes(digest) || !sameFiles) {
  if (check) { console.error('extension/lib/phone-pins.js does not pin the current phone/ files: run npm run build'); stale++; }
  else {
    const next = [digest, ...pins.filter((p) => p !== digest)].slice(0, KEEP_PINS);
    writeFileSync(pinsFile, `// Generated by scripts/build.mjs: do not edit.
// SHA-256 digests of the phone approval page versions this extension trusts,
// newest first. The extension checks the published page against these before
// it sends anything to your phone.
export const PHONE_FILES = ${JSON.stringify(files)};
export const PHONE_PINS = ${JSON.stringify(next, null, 2)};
`);
    console.log(`pinned phone page ${digest.slice(0, 12)}`);
  }
}
if (stale) process.exit(1);
